def load_log() -> List[Record]:
    """Load the embedded CSV log into structured records."""
    filtered_lines = []
    for line in io.StringIO(LOG_DATA):
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("#"):
            stripped = stripped.lstrip("# ")
        filtered_lines.append(stripped)
    reader = csv.DictReader(filtered_lines)
    records: List[Record] = []
    for row in reader:
        records.append(
            Record(
                tick=int(row["_tick"]),
                time=float(row["_time"]),
                frames=int(row["frames"]),
                mean_episode_return_player_0=float(row["mean_episode_return_player_0"]),
                loss_player_0=float(row["loss_player_0"]),
                mean_episode_return_player_1=float(row["mean_episode_return_player_1"]),
                loss_player_1=float(row["loss_player_1"]),
            )
        )
    return records


@dataclass
class Summary:
    frames: int
    mean_return_p0: float
    mean_return_p1: float
    loss_p0: float
    loss_p1: float


@dataclass
class WindowStats:
    window_size: int
    frame_start: int
    frame_end: int
    mean_return_p0: float
    mean_return_p1: float
    std_return_p0: float
    std_return_p1: float
    trend_return_p0: float
    trend_return_p1: float
    mean_loss_p0: float
    mean_loss_p1: float


@dataclass
class TrainingAssessment:
    seat_edge_recent: float
    seat_edge_previous: float | None
    seat_edge_entire: float
    verdict: str
    observations: List[str]


def compute_summary(records: Iterable[Record]) -> Summary:
    """Return summary statistics from the final row of the log."""
    record_list = list(records)
    if not record_list:
        raise ValueError("No records found in training log")
    last = record_list[-1]
    return Summary(
        frames=last.frames,
        mean_return_p0=last.mean_episode_return_player_0,
        mean_return_p1=last.mean_episode_return_player_1,
        loss_p0=last.loss_player_0,
        loss_p1=last.loss_player_1,
    )


def _mean(values: Sequence[float]) -> float:
    return sum(values) / len(values)


def _std(values: Sequence[float]) -> float:
    if len(values) < 2:
        return 0.0
    mean_value = _mean(values)
    variance = sum((v - mean_value) ** 2 for v in values) / (len(values) - 1)
    return math.sqrt(variance)


def _linear_trend(frames: Sequence[int], values: Sequence[float]) -> float:
    """Return slope of simple linear regression per million frames."""
    if len(values) < 2:
        return 0.0
    # scale frames to millions to keep numbers manageable
    xs = [f / 1_000_000 for f in frames]
    mean_x = _mean(xs)
    mean_y = _mean(values)
    numerator = sum((x - mean_x) * (y - mean_y) for x, y in zip(xs, values))
    denominator = sum((x - mean_x) ** 2 for x in xs)
    if denominator == 0:
        return 0.0
    return numerator / denominator


def compute_window_stats(records: Sequence[Record], window_size: int) -> WindowStats:
    if window_size <= 0:
        raise ValueError("window_size must be positive")
    if window_size > len(records):
        window_records = list(records)
    else:
        window_records = list(records[-window_size:])

    frames = [r.frames for r in window_records]
    returns_p0 = [r.mean_episode_return_player_0 for r in window_records]
    returns_p1 = [r.mean_episode_return_player_1 for r in window_records]
    losses_p0 = [r.loss_player_0 for r in window_records]
    losses_p1 = [r.loss_player_1 for r in window_records]

    return WindowStats(
        window_size=len(window_records),
        frame_start=frames[0],
        frame_end=frames[-1],
        mean_return_p0=_mean(returns_p0),
        mean_return_p1=_mean(returns_p1),
        std_return_p0=_std(returns_p0),
        std_return_p1=_std(returns_p1),
        trend_return_p0=_linear_trend(frames, returns_p0),
        trend_return_p1=_linear_trend(frames, returns_p1),
        mean_loss_p0=_mean(losses_p0),
        mean_loss_p1=_mean(losses_p1),
    )


def describe_window(stats: WindowStats, label: str) -> str:
    return (
        f"{label} (last {stats.window_size} points, frames {stats.frame_start:,}–{stats.frame_end:,}):\n"
        f"  mean returns -> P0: {stats.mean_return_p0:+.4f}, P1: {stats.mean_return_p1:+.4f}\n"
        f"  return stdev -> P0: {stats.std_return_p0:.4f}, P1: {stats.std_return_p1:.4f}\n"
        f"  trend (per 1M frames) -> P0: {stats.trend_return_p0:+.4f}, P1: {stats.trend_return_p1:+.4f}\n"
        f"  mean losses -> P0: {stats.mean_loss_p0:.4f}, P1: {stats.mean_loss_p1:.4f}"
    )


def _seat_edge(stats: WindowStats) -> float:
    """Approximate the separation between seats for a given window."""

    return stats.mean_return_p0 - stats.mean_return_p1


def assess_training(
    recent: WindowStats,
    entire: WindowStats,
    previous: WindowStats | None = None,
) -> TrainingAssessment:
    """Return a qualitative interpretation of the latest training dynamics."""

    observations: List[str] = []

    recent_edge = _seat_edge(recent)
    entire_edge = _seat_edge(entire)
    previous_edge: float | None = None
    if previous is not None:
        previous_edge = _seat_edge(previous)

    # Seat advantage commentary.
    if abs(recent_edge) < 0.01:
        observations.append(
            "Seat advantage remains nearly neutral; policies are closely matched."
        )
    elif recent_edge > 0:
        observations.append(
            "Player 0 keeps a noticeable edge over Player 1 in the latest window."
        )
    else:
        observations.append(
            "Player 1 has overtaken Player 0 in the recent evaluations."
        )

    # Momentum via return slopes.
    slope_threshold = 0.01
    if abs(recent.trend_return_p0) < slope_threshold and abs(recent.trend_return_p1) < slope_threshold:
        observations.append(
            "Return trends are flat, signalling a plateau around the current policy quality."
        )
    else:
        trend_direction: List[str] = []
        if recent.trend_return_p0 >= slope_threshold:
            trend_direction.append("Player 0 is still improving")
        elif recent.trend_return_p0 <= -slope_threshold:
            trend_direction.append("Player 0 is slipping")
        if recent.trend_return_p1 >= slope_threshold:
            trend_direction.append("Player 1 is improving")
        elif recent.trend_return_p1 <= -slope_threshold:
            trend_direction.append("Player 1 is regressing")
        if trend_direction:
            observations.append(
                ", and ".join(trend_direction) + " over the last window."
            )

    # Compare recent seat edge and losses against the previous window when available.
    if previous is not None:
        delta_edge = recent_edge - previous_edge  # type: ignore[operator]
        if abs(delta_edge) < 0.005:
            observations.append(
                "Seat gap changed only marginally compared to the prior window."
            )
        elif delta_edge > 0:
            observations.append(
                "Seat gap widened relative to the prior window, benefitting Player 0."
            )
        else:
            observations.append(
                "Seat gap narrowed relative to the prior window, benefitting Player 1."
            )

        loss_shift_p0 = recent.mean_loss_p0 - previous.mean_loss_p0
        loss_shift_p1 = recent.mean_loss_p1 - previous.mean_loss_p1
        if abs(loss_shift_p0) < 0.01 and abs(loss_shift_p1) < 0.01:
            observations.append("Losses are stable frame-to-frame across windows.")
        else:
            observations.append(
                (
                    "Losses moved by"
                    f" ΔP0={loss_shift_p0:+.3f}, ΔP1={loss_shift_p1:+.3f}"
                    ", signalling optimisation dynamics are still shifting."
                )
            )
    else:
        observations.append(
            "Not enough history for a previous-window comparison of losses or seat gap."
        )

    # Volatility commentary using the larger of the seat deviations.
    volatility = max(recent.std_return_p0, recent.std_return_p1)
    if volatility > 0.02:
        observations.append(
            "High volatility persists; expect swings in short-term averages."
        )
    elif volatility > 0.01:
        observations.append(
            "Moderate volatility remains, but the averages are stabilising."
        )
    else:
        observations.append("Return variance is low, indicating consistent evaluations.")

    # Craft a high-level verdict that answers whether training is on track.
    if abs(recent_edge) < 0.01 and abs(recent.trend_return_p0) < slope_threshold:
        verdict = (
            "Training has reached a slow, balanced plateau—continue accumulating more"
            " frames or adjust curriculum to break symmetry."
        )
    elif recent_edge > 0 and recent.trend_return_p0 >= -slope_threshold:
        verdict = (
            "Training is on track: Player 0 keeps a mild advantage, though gains are"
            " incremental. Staying the course with more frames should clarify the edge."
        )
    elif recent_edge < 0 and recent.trend_return_p1 >= -slope_threshold:
        verdict = (
            "Player 1 is converging better in the latest window; investigate whether the"
            " lead swap aligns with expectations or requires balancing tweaks."
        )
    else:
        verdict = (
            "Momentum slipped despite the current edge—consider extending training while"
            " monitoring for further degradation before changing hyperparameters."
        )

    return TrainingAssessment(
        seat_edge_recent=recent_edge,
        seat_edge_previous=previous_edge,
        seat_edge_entire=entire_edge,
        verdict=verdict,
        observations=observations,
    )


def plot_training_curves(records: List[Record], out_path: Path | None = None) -> Path:
    """Plot mean returns and losses for both players over frames.

    Raises:
        RuntimeError: if matplotlib is not available in the environment.
    """
    if plt is None:
        raise RuntimeError(
            "matplotlib is not installed. Install it to generate plots"
        )
    fig, axes = plt.subplots(2, 1, figsize=(10, 8), sharex=True)

    frames = [r.frames for r in records]
    axes[0].plot(frames, [r.mean_episode_return_player_0 for r in records], label="Player 0 mean return")
    axes[0].plot(frames, [r.mean_episode_return_player_1 for r in records], label="Player 1 mean return")
    axes[0].axhline(0, color="black", linewidth=0.8, linestyle="--")
    axes[0].set_ylabel("Mean episode return")
    axes[0].legend(loc="upper right")
    axes[0].set_title("Continuing run performance")

    axes[1].plot(frames, [r.loss_player_0 for r in records], label="Player 0 loss")
    axes[1].plot(frames, [r.loss_player_1 for r in records], label="Player 1 loss")
    axes[1].set_ylabel("Loss")
    axes[1].set_xlabel("Frames")
    axes[1].legend(loc="upper right")

    fig.tight_layout()

    if out_path is None:
        out_path = Path("continuing_run_curves.png")

    fig.savefig(out_path)
    plt.close(fig)
    return out_path


